package creative

import (
	"context"
	"errors"
	"time"

	"github.com/TokenFlux/TokenRouter/internal/protocol"
)

// result_delivery.go records billable provider outcomes before saving
// generated images for temporary delivery.
// A generated image becomes billable provider work before its bytes become
// available for client retrieval. Delivery first records provider identity,
// success timing, output metadata, and settlement recovery through
// ProviderOutcomeStore. The transient save phase therefore begins only after
// that durable fact can be used by later recovery.
//
// Each successful output receives up to three save attempts inside one shared
// five-second context budget, with one-second waits between failures. Parent
// cancellation stops the phase with an error, while an exhausted save budget
// marks delivery lost and leaves the output succeeded as a provider-work fact.
// Lost checks distinguish confirmed absence from storage-read failures,
// allowing settlement to retry uncertain availability rather than treating
// every outage as permanent loss.

// These output error codes distinguish pending transient saves from confirmed
// delivery loss while successful output status continues to identify billable
// provider work.
const (
	OutputDeliveryPending = "DELIVERY_PENDING" // transient output save pending
	OutputDeliveryLost    = "DELIVERY_LOST"    // confirmed transient delivery loss
)

// ProviderOutput contains a provider result; image bytes pass through worker
// memory and temporary storage.
type ProviderOutput struct {
	// Success controls whether Bytes must be nonempty and saved; Mime labels the
	// delivered data. ErrorCode and ErrorMessage describe failed provider outputs.
	// Keep the byte slice stable while synchronous delivery consumes this value.
	Index        int    // provider output delivery index
	Success      bool   // provider work success flag
	Bytes        []byte // transient generated image bytes
	Mime         string // provider output MIME label
	ErrorCode    string // provider output failure code
	ErrorMessage string // provider output public error text
}

// ProviderOutcomeStore records provider success, output metadata, and recovery
// work in one transaction.
type ProviderOutcomeStore interface {
	// RecordProviderOutcome records provider timing, identity, output metadata,
	// and settlement recovery together. The successful return is the durable fact
	// used before image bytes are saved in transient storage. Implementations
	// retain a cancelled task state when recording completed provider work and
	// treat an already recorded outcome as a repeat, allowing delivery recovery
	// to proceed from that stored fact instead of requesting generation again.
	RecordProviderOutcome(context.Context, string, int64, []CreativeRunOutput, time.Time) error
	// CompleteProviderOutcome records actual cost and delivered or lost status
	// for previously recorded provider work. Completion retains cancelled status
	// when applicable and uses the implementation state/version rules to report
	// conflicting updates.
	CompleteProviderOutcome(context.Context, string, float64, bool, time.Time) error
}

// ResultDelivery records provider outcomes and saves generated images for
// client retrieval.
type ResultDelivery struct {
	// Outcomes records the durable provider fact before Repo updates delivery
	// metadata. Store holds image bytes during the configured TTL; missing byte
	// storage can mark saves lost while its read checks return unavailable.
	// Now supplies the clock used for outcome and expiry metadata. A nil callback
	// uses system time; callers keep the clock stable during a delivery operation.
	Now      func() time.Time       // optional delivery clock callback
	Repo     CreativeRunRepository  // output metadata update repository
	Outcomes ProviderOutcomeStore   // provider outcome persistence implementation
	Store    CreativeTransientStore // temporary generated image byte storage
	// TTL supplies both saved expiry metadata and transient output lifetime.
	// Configure a positive value so a store default cannot disagree with metadata.
	TTL time.Duration // generated byte retention duration
}

// Record persists provider outcome metadata before saving each successful
// output for retrieval. Successful outputs require nonempty bytes; failed
// outputs retain their error metadata and are not saved.
//
// All saves share a five-second child context, with at most three attempts per
// output and one-second waits between failures. Parent cancellation returns
// its error before final output updates. Other exhausted saves assign
// DELIVERY_LOST while retaining succeeded output status, which represents
// completed provider work for settlement. Metadata update errors propagate
// after the durable outcome exists, so callers can resume recovery without
// another generation call.
func (d ResultDelivery) Record(ctx context.Context, id string, providerID int64, outputs []ProviderOutput) error {
	if d.Outcomes == nil {
		return errors.New("creative platform outcome store is not configured")
	}
	now := d.now()
	expires := now.Add(d.TTL)
	metadata := make([]CreativeRunOutput, 0, len(outputs))
	for _, output := range outputs {
		status := CreativeRunOutputStatusFailed
		code, message := output.ErrorCode, output.ErrorMessage
		if output.Success {
			if len(output.Bytes) == 0 {
				return ErrCreativeTransientFailed.WithCause(errors.New("creative output is empty"))
			}
			status = CreativeRunOutputStatusSucceeded
			code = OutputDeliveryPending
			message = ""
		}
		frameCount := 0
		if output.Success && output.Mime == "image/gif" {
			info, err := protocol.ParseGIFMetadata(output.Bytes)
			if err != nil {
				return ErrCreativeTransientFailed.WithCause(err)
			}
			frameCount = info.FrameCount
		}
		mime := output.Mime
		size := int64(len(output.Bytes))
		metadata = append(metadata, CreativeRunOutput{FrameCount: frameCount, RunID: id, OutputIndex: output.Index, Status: status, MimeType: &mime, ByteSize: &size, TransientExpiresAt: &expires, ErrorCode: &code, ErrorMessage: &message})
	}
	// Commit the provider-work fact and recovery metadata before storing image
	// bytes. A failed transient save after this point still leaves enough durable
	// evidence for settlement to charge the generated work and classify delivery.
	if err := d.Outcomes.RecordProviderOutcome(ctx, id, providerID, metadata, now); err != nil {
		return err
	}
	// Bound transient save retries across all outputs under the worker context.
	// A lease or shutdown cancellation interrupts the same budget, while its own
	// expiry lets completed provider work proceed with a delivery-loss marker.
	saveCtx, cancel := context.WithTimeout(ctx, 5*time.Second)
	defer cancel()
	for _, output := range outputs {
		if !output.Success {
			continue
		}
		var saved bool
		// Retry storage of these already generated bytes, not provider execution.
		// Keep failures inside the shared budget so an unavailable
		// transient store
		// can end in billable delivery loss instead of unbounded byte retention.
		for attempt := range 3 {
			if saveCtx.Err() != nil {
				break
			}
			if d.Store != nil && d.Store.SaveOutput(saveCtx, id, output.Index, output.Bytes, d.TTL) == nil {
				saved = true
				break
			}
			if attempt < 2 {
				timer := time.NewTimer(time.Second)
				select {
				case <-saveCtx.Done():
					timer.Stop()
				case <-timer.C:
				}
			}
		}
		if ctx.Err() != nil {
			return ctx.Err()
		}
		code := ""
		// Provider success remains true after save exhaustion. Record
		// the loss code
		// alongside that success so settlement still counts the work
		// while refusing
		// to advertise the image as delivered.
		if !saved {
			code = OutputDeliveryLost
		}
		if err := d.Repo.UpdateCreativeRunOutput(ctx, id, output.Index, CreativeRunOutputStatusSucceeded, output.Mime, int64(len(output.Bytes)), &expires, code, ""); err != nil {
			return err
		}
	}
	return nil
}

// Lost checks succeeded outputs for a delivery-loss marker or confirmed
// transient absence. Nil and other-status outputs are skipped; a missing
// store returns unavailable when an unmarked succeeded output needs reading.
//
// Known loss accumulates across the relevant outputs, but any other read
// failure stops the scan and returns false with that error, even after an
// earlier output was confirmed lost. Settlement can then retry availability
// classification for the complete set rather than finalizing a loss decision
// while a remaining image read is uncertain. DELIVERY_LOST entries require no
// read because their metadata already records the exhausted save result.
func (d ResultDelivery) Lost(ctx context.Context, id string, outputs []*CreativeRunOutput) (bool, error) {
	lost := false
	for _, output := range outputs {
		if output == nil || output.Status != CreativeRunOutputStatusSucceeded {
			continue
		}
		if output.ErrorCode != nil && *output.ErrorCode == OutputDeliveryLost {
			lost = true
			continue
		}
		if d.Store == nil {
			return false, ErrCreativeTransientUnavailable
		}
		_, err := d.Store.LoadOutput(ctx, id, output.OutputIndex)
		if errors.Is(err, ErrCreativeTransientNotFound) {
			lost = true
			continue
		}
		// A later read error overrides any earlier accumulated loss result. Leave
		// settlement pending with this uncertainty so a complete availability scan
		// can decide delivery after the store becomes readable.
		if err != nil {
			return false, err
		}
	}
	return lost, nil
}

// now returns the configured delivery clock value, or current system time
// when the callback is absent. Callers keep Now stable while shared delivery
// operations calculate their output expiry deadlines.
func (d ResultDelivery) now() time.Time {
	if d.Now != nil {
		return d.Now()
	}
	return time.Now()
}
