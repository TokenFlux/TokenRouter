// checks.test.mjs exercises comment, dependency, and UI-token checks with source
// fixtures that resemble their supported languages. Formatting the fixtures
// protects the scope of local UI exceptions, while positive controls prove that
// neighboring violations continue to be reported by each check.

// Static assets and generated files are excluded only at their configured root.
// Nested public pages and handwritten same-named configuration modules must remain checked.
test('source collection keeps nested public pages and handwritten configuration files', (context) => {
  const directory = mkdtempSync(join(tmpdir(), 'tokenrouter-source-scope-'))
  context.after(() => rmSync(directory, { recursive: true, force: true }))
  for (const file of [
    'public/resource.js',
    'vite.config.js',
    'src/views/public/Page.vue',
    'src/config/vite.config.js',
  ]) {
    const target = join(directory, file)
    mkdirSync(dirname(target), { recursive: true })
    writeFileSync(target, '// fixture source')
  }
  assert.deepEqual(
    collectSourceFiles(directory, directory).map((file) => relative(directory, file)),
    ['src/config/vite.config.js', 'src/views/public/Page.vue'],
  )
})

// Comment fixtures contain translated user text and misleading comment markers.
// The parser must report actual prose comments while preserving application strings.
test('comment checks distinguish strings, regular expressions, and actual comments', () => {
  const text = `// sample.ts checks source comments for the fixture.\nconst text = "// 中文"\nconst template = \`/* 中文 */\`\nconst pattern = /中文/\n// 中文说明\n`
  const issues = checkComments(text, 'sample.ts')
  assert.equal(issues.length, 1)
  assert.equal(issues[0].line, 5)
})

// Vue exposes separate template, script, and style comment syntaxes in one file.
// Every explanatory block is checked while translated template content remains valid.
test('Vue checks actual comments in all three component blocks', () => {
  const source = `<!-- Sample.vue displays a translated message. -->
<template><!-- 中文模板 --><p>中文内容</p></template>
<script setup lang="ts">const label = '中文' // 中文脚本
</script>
<style>/* 中文样式 */p::after {content:'中文'}</style>`
  const issues = checkComments(source, 'Sample.vue')
  assert.equal(issues.length, 3)
  assert.ok(issues.every((issue) => issue.message.includes('English')))
})

// A filename change makes an existing overview stale even when it is English.
// Generated headers and license notices retain their documented exemptions.
test('overview names and generated exemptions use parsed comment tokens', () => {
  assert.equal(checkComments('// Old.ts describes a module.\nexport {}', 'New.ts').length, 1)
  assert.deepEqual(
    checkComments('// Code generated by fixture. DO NOT EDIT.\n// 中文\nexport {}', 'generated.ts'),
    [],
  )
  assert.equal(
    checkComments('const text = "Code generated by fixture. DO NOT EDIT."', 'manual.ts').length,
    1,
  )
  assert.deepEqual(
    checkComments(
      '// License.ts provides the fixture.\n/* Copyright 中文作者 */\nexport {}',
      'License.ts',
    ),
    [],
  )
  assert.equal(checkComments('const value = 1', 'sample.test.ts').length, 1)
  assert.equal(
    checkComments('// old.test.ts checks a fixture.\nconst value = 1', 'sample.test.ts').length,
    1,
  )
  assert.deepEqual(
    checkComments('// sample.test.ts checks a fixture.\nconst value = 1', 'sample.test.ts'),
    [],
  )
})

// A broken script block cannot supply reliable comment or dependency information.
// The parser propagates its error so command entry points fail closed.
test('invalid syntax fails parsing instead of skipping a source block', () => {
  assert.throws(() => parseSource('<script setup lang="ts">const =</script>', 'Invalid.vue'))
  assert.throws(() =>
    parseSource('<template><p :class="(/* hidden */" /></template>', 'Invalid.vue'),
  )
})

// Static import forms include re-exports, lazy imports, and type-only references.
// Relative paths and aliases receive the same API ownership restrictions.
test('imports enforce API layers across static module reference forms', () => {
  const text = `import type { A } from '../components/A.vue'
export { B } from '@/views/B.vue'
const load = () => import('@/stores/auth')
import type { User } from './user.types'
`
  assert.equal(checkImports(text, 'src/api/example.ts').length, 3)
  assert.equal(checkImports("import X from '@/components/X.vue'", 'src/components/Y.ts').length, 0)
  assert.equal(checkImports("import X from '@/views/X.vue'", 'src/components/Y.ts').length, 1)
  assert.equal(
    checkImports("import X from '@/components/X.vue'", 'src/composables/useX.ts').length,
    1,
  )
})

// Private provider files can cooperate internally and expose their declared route entry.
// An unrelated page remains forbidden from reaching into the implementation folder.
test('private ownership admits declared entries and rejects external implementation imports', () => {
  assert.equal(
    importViolation(
      'src/views/admin/providers/ProvidersView.vue',
      'src/views/admin/providers/useList',
    ),
    null,
  )
  assert.equal(
    importViolation('src/router/admin.ts', 'src/views/admin/providers/ProvidersView.vue'),
    null,
  )
  assert.ok(importViolation('src/router/admin.ts', 'src/views/admin/providers/useList'))
  assert.ok(importViolation('src/views/user/KeysView.vue', 'src/views/admin/providers/useList'))
  assert.equal(
    importViolation('src/views/admin/SettingsView.vue', 'src/views/admin/settings/useSettings'),
    null,
  )
  assert.ok(
    importViolation('src/views/admin/OtherView.vue', 'src/views/admin/settings/useSettings'),
  )
  for (const [directory, owner] of [
    ['src/views/user/payment/', 'src/views/user/PaymentView.vue'],
    ['src/views/admin/risk-control/', 'src/views/admin/RiskControlView.vue'],
  ]) {
    assert.equal(importViolation(owner, `${directory}privateHelper`), null)
    assert.equal(importViolation(`${directory}child.ts`, `${directory}privateHelper`), null)
    assert.ok(importViolation('src/views/unrelated.vue', `${directory}privateHelper`))
  }
  assert.equal(
    importViolation(
      'src/__tests__/integration/data-import.spec.ts',
      'src/views/admin/providers/operations/ImportDataModal.vue',
    ),
    null,
  )
  assert.ok(
    importViolation(
      'src/__tests__/integration/data-import.spec.ts',
      'src/views/admin/providers/operations/BulkEditProviderModal.vue',
    ),
  )
  assert.ok(
    importViolation(
      'src/__tests__/integration/unrelated.spec.ts',
      'src/views/admin/providers/operations/ImportDataModal.vue',
    ),
  )
})

// A parent element exemption addresses its own opening tag even after attribute wrapping.
// Descendant and sibling elements still expose their separate stacking violations.
test('HTML exceptions remain local to the owning opening tag after formatting', async () => {
  const source = `<template><div data-description="a long attribute forcing the opening tag to wrap" class="z-[1]"><!-- check-ui-allow: local parent layer --><span class="z-[2]"></span></div><aside class="z-[3]"></aside></template>`
  for (const text of [source, await format(source, { parser: 'vue', printWidth: 45 })]) {
    assert.equal(
      checkUI(text, 'Example.vue').filter((issue) => issue.ruleId === 'arbitrary-z').length,
      2,
    )
  }
})

// CSS exceptions attach to one declaration, including a declaration wrapped by formatting.
// A neighboring declaration with another literal layer remains an observable positive control.
test('CSS declaration exceptions survive formatting and keep siblings checked', async () => {
  const source = `.first { z-index: 12345 !important; /* check-ui-allow: external widget layer */ } .second { z-index: 2; }`
  for (const text of [source, await format(source, { parser: 'css', printWidth: 30 })]) {
    assert.equal(
      checkUI(text, 'example.css').filter((issue) => issue.ruleId === 'z-index-literal').length,
      1,
    )
  }
})

// A CSS comment can end immediately before a declaration without intervening space.
// Its range must stop at the comment boundary so the following violation remains visible.
test('CSS comment ranges do not consume the following declaration character', async () => {
  const source = '.sample{/* local note */border-radius:3px;}'
  for (const text of [source, await format(source, { parser: 'css' })]) {
    const parsed = parseSource(text, 'sample.css')
    assert.equal(text.slice(...parsed.comments[0].range), '/* local note */')
    assert.equal(
      checkUI(text, 'sample.css').filter((issue) => issue.ruleId === 'raw-border-radius').length,
      1,
    )
  }
})

// JavaScript exceptions address complete statements containing wrapped method calls.
// A later statement is checked independently, and marker strings cannot grant an exemption.
test('JavaScript statement exceptions survive formatting and ignore marker strings', async () => {
  const source = `const theme = document.documentElement.classList.contains('dark') // check-ui-allow: direct theme primitive
const other = document.documentElement.classList.contains('dark')
const fake = 'check-ui-allow'; const style = { zIndex: 3 }
`
  for (const text of [source, await format(source, { parser: 'typescript', printWidth: 35 })]) {
    const issues = checkUI(text, 'example.ts')
    assert.equal(issues.filter((issue) => issue.ruleId === 'nonreactive-dark').length, 1)
    assert.equal(issues.filter((issue) => issue.ruleId === 'z-index-literal').length, 1)
  }
})

// Comments may document prohibited classes while literal source still needs checking.
// Semantic radius variables pass and arbitrary radius values continue to fail.
test('UI rules exclude documentation and enforce radius values', () => {
  const source =
    '/* rounded-sm z-[1] */ .a { border-radius: var(--radius-control); } .b { border-radius: 3px; }'
  assert.deepEqual(
    checkUI(source, 'sample.css').map((issue) => issue.ruleId),
    ['raw-border-radius'],
  )
  assert.deepEqual(
    checkTailwindConfig(
      "export default {borderRadius: {control: 'var(--radius-control)'}, maxHeight: {menu: 'var(--max-h-menu)'}}",
    ),
    [],
  )
  assert.equal(
    checkTailwindConfig("export default {borderRadius: {sm:'2px'}, maxHeight: {menu:'20rem'}}")
      .length,
    2,
  )
})

// A trailing exception inside a function belongs to its preceding local statement.
// Sibling statements remain checked even though the function and block enclose both.
test('nested statement exceptions do not exempt their enclosing function body', async () => {
  const source = `function draw() {
  const first = { zIndex: 1 } // check-ui-allow: local first overlay
  const second = { zIndex: 2 }
  // check-ui-allow: local third overlay
  const third = { zIndex: 3 }
  return second
}`
  for (const text of [source, await format(source, { parser: 'typescript', printWidth: 30 })]) {
    assert.equal(
      checkUI(text, 'example.ts').filter((issue) => issue.ruleId === 'z-index-literal').length,
      1,
    )
  }
})

// Formatting can move a boundary block marker away from its preceding statement.
// The following statement or sibling element remains its owner, while the first violation stays reported.
test('boundary block markers preserve the same owner after formatting', async () => {
  for (const [filename, parser, source, expected] of [
    [
      'sample.ts',
      'typescript',
      'const first={zIndex:1}; /* check-ui-allow: following statement owns this layer */ const second={zIndex:2};',
      /^zIndex\s*:\s*1/,
    ],
    [
      'Sample.vue',
      'vue',
      '<template><div class="z-[1]"></div><!-- check-ui-allow: following element owns this layer --><span class="z-[2]"></span></template>',
      /^z-\[1\]/,
    ],
  ]) {
    for (const text of [source, await format(source, { parser })]) {
      const issues = checkUI(text, filename)
      assert.equal(issues.length, 1)
      const issue = issues[0]
      assert.match(text.split('\n')[issue.line - 1].slice(issue.column - 1), expected)
    }
  }
})

// Template expressions can contain JavaScript comments inside attribute and interpolation syntax.
// Their comment tokens are checked alongside HTML comments rather than treated as translated text.
test('Vue template expression comments are checked as actual comment tokens', () => {
  const source =
    '<!-- Example.vue displays a value. --><template><p :class="/* 中文 */ value as string">{{ /* 中文 */ value }}</p></template>'
  assert.equal(checkComments(source, 'Example.vue').length, 2)
})

// Plugin host implementation may compose shared controls and application stores.
// Reverse imports would expose execution internals to foundational layers, so those edges remain forbidden.
test('plugin host dependency direction preserves shared layer ownership', () => {
  assert.equal(importViolation('src/pluginHost/hostApi.ts', 'src/stores/auth'), null)
  assert.equal(
    importViolation('src/pluginHost/components.ts', 'src/components/common/Input.vue'),
    null,
  )
  assert.equal(importViolation('src/views/plugin/Page.vue', 'src/pluginHost/runtime'), null)
  assert.ok(importViolation('src/pluginHost/runtime.ts', 'src/views/plugin/Page.vue'))
  assert.ok(importViolation('src/api/plugins.ts', 'src/pluginHost/runtime'))
  assert.ok(importViolation('src/components/common/Input.vue', 'src/pluginHost/runtime'))
})
